use serde::{Deserialize, Serialize};

use crate::error::AppResult;
use crate::hardware::SystemReport;

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Cs2Optimization {
    pub launch_options: String,
    pub autoexec: String,
    pub video_settings: VideoSettingsRecommendation,
    pub notes: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct VideoSettingsRecommendation {
    pub resolution: String,
    pub display_mode: String,
    pub refresh_hz: u32,
    pub v_sync: String,
    pub anti_aliasing: String,
    pub global_shadow_quality: String,
    pub model_texture_detail: String,
    pub effect_detail: String,
    pub shader_detail: String,
    pub multicore_rendering: bool,
    pub fps_max: u32,
}

pub fn build_cs2_plan(report: &SystemReport) -> AppResult<Cs2Optimization> {
    let hz = report
        .monitors
        .iter()
        .filter_map(|m| m.refresh_hz)
        .max()
        .unwrap_or(144);

    let tier = gpu_tier(&report.gpu.model);
    let (aa, shadows, effects) = match tier {
        GpuTier::High => ("2x MSAA", "Medium", "Low"),
        GpuTier::Mid => ("None", "Low", "Low"),
        GpuTier::Low => ("None", "Low", "Low"),
    };

    let res = report
        .monitors
        .first()
        .and_then(|m| m.resolution.clone())
        .unwrap_or_else(|| "1920x1080".into());

    let launch_options = format!(
        "-high -novid -nojoy +fps_max {} +exec boostx_autoexec.cfg",
        hz.min(400)
    );

    let fps_cap = hz.min(400);
    let autoexec = format!(
        r#"// Generated by BoostX — review before competitive play
fps_max {fps_cap}
cl_interp_ratio 1
cl_interp 0.015625
rate 786432
mm_dedicated_search_maxping 50
r_dynamic 0
r_drawtracers_firstperson 1
"#
    );

    let video = VideoSettingsRecommendation {
        resolution: res,
        display_mode: "Fullscreen".into(),
        refresh_hz: hz,
        v_sync: "Disabled".into(),
        anti_aliasing: aa.into(),
        global_shadow_quality: shadows.into(),
        model_texture_detail: if tier == GpuTier::High {
            "High"
        } else {
            "Medium"
        }
        .into(),
        effect_detail: effects.into(),
        shader_detail: "Low".into(),
        multicore_rendering: true,
        fps_max: hz.min(400),
    };

    let notes = vec![
        "Use NVIDIA Reflex / AMD Anti-Lag+ if available in CS2 video settings.".into(),
        "After copying autoexec, add host_writeconfig once in console to persist.".into(),
        format!(
            "Detected {} CPU — keep multicore rendering enabled.",
            report.cpu.vendor
        ),
    ];

    Ok(Cs2Optimization {
        launch_options,
        autoexec,
        video_settings: video,
        notes,
    })
}

#[derive(PartialEq)]
enum GpuTier {
    High,
    Mid,
    Low,
}

fn gpu_tier(model: &str) -> GpuTier {
    let u = model.to_uppercase();
    if u.contains("4090")
        || u.contains("4080")
        || u.contains("7900")
        || u.contains("4070 TI")
        || u.contains("3080")
    {
        GpuTier::High
    } else if u.contains("3060") || u.contains("4060") || u.contains("6700") || u.contains("2060") {
        GpuTier::Low
    } else {
        GpuTier::Mid
    }
}
