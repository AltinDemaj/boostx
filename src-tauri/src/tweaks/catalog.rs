pub fn all_tweaks() -> Vec<TweakDefinition> {
    let mut v = base_tweaks();
    v.extend(super::catalog_extended::tweaks());
    v.extend(super::catalog_competitive_extra::tweaks());
    v.extend(super::catalog_network_deep::tweaks());
    v
}

pub fn tweaks_for_profile(
    profile: super::metadata::OptimizationProfile,
    report: &crate::hardware::SystemReport,
) -> Vec<TweakDefinition> {
    all_tweaks()
        .into_iter()
        .filter(|t| t.profiles.contains(&profile))
        .filter(|t| super::engine::hardware_matches(t, report))
        .collect()
}
