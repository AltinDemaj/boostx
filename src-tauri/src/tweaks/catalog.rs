fn competitive() -> Vec<OptimizationProfile> {
    vec![OptimizationProfile::Competitive, OptimizationProfile::Balanced]
}

pub(crate) fn reg(
    hive: &str,
    path: &str,
    name: &str,
    data: serde_json::Value,
) -> RegistryWrite {
    RegistryWrite {
        hive: hive.into(),
        path: path.into(),
        value_name: name.into(),
        kind: "REG_DWORD".into(),
        data,
    }
}

